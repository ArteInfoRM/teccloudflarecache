    private function getFormValues()
    {
        $token = (string) Configuration::get(self::CFG_TOKEN);

        return [
            'TECCFC_TOKEN' => $token === '' ? '' : self::TOKEN_MASK . substr($token, -4),
            'TECCFC_ZONE_ID' => (string) Configuration::get(self::CFG_ZONE_ID),
            'TECCFC_ZONE_NAME' => (string) Configuration::get(self::CFG_ZONE_NAME),
            'TECCFC_SYNC_WITH_PS' => (int) Configuration::get(self::CFG_SYNC_WITH_PS),
            'TECCFC_BYPASS_ADMIN' => (int) Configuration::get(self::CFG_BYPASS_ADMIN),
            'TECCFC_BYPASS_URLS' => (string) Configuration::get(self::CFG_BYPASS_URLS),
            'TECCFC_MONITOR_URL' => (string) Configuration::get(self::CFG_MONITOR_URL),
        ];
    }

    /**
     * Creates an API client from validated stored configuration.
     *
     * @return TecCloudflareCacheClient API client
     */
    private function getClient()
    {
        return new TecCloudflareCacheClient((string) Configuration::get(self::CFG_TOKEN), (string) Configuration::get(self::CFG_ZONE_ID));
    }

    /**
     * Checks whether a Cloudflare API call can be attempted.
     *
     * @return bool Whether credentials are present
     */
    private function isCloudflareConfigured()
    {
        return (string) Configuration::get(self::CFG_TOKEN) !== '' && (string) Configuration::get(self::CFG_ZONE_ID) !== '';
    }

    /**
     * Displays all validation errors using PrestaShop's admin UI.
     *
     * @param string[] $errors Error messages
     *
     * @return string Rendered error markup
     */
    private function formatErrors($errors)
    {
        $output = '';
        foreach ($errors as $error) {
            $output .= $this->displayError($error);
        }

        return $output;
    }

    /**
     * Adds a redacted operation message to PrestaShop logs.
     *
     * @param string $message Safe diagnostic message
     * @param int $severity PrestaShop log severity
     *
     * @return void
     */
    private function log($message, $severity)
    {
        PrestaShopLogger::addLog('Tec Cloudflare Cache: ' . substr($message, 0, 500), $severity, null, 'Teccloudflarecache', (int) $this->id, true);
    }

    /**
     * Removes control characters from a transport diagnostic.
     *
     * @param string $message Raw transport error
     *
     * @return string Safe diagnostic message
     */
    private function sanitizeDiagnostic($message)
    {
        return preg_replace('/[^A-Za-z0-9 .,:;()_-]/', '', substr($message, 0, 180));
    }
}
